// Package codegen emits the typed Go API from schema IR.
package codegen

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
	"unicode"

	"github.com/eji/tiqq/schema"
)

type Config struct {
	Package string
}

// Generate emits typed tables with generic InnerJoin and LeftJoin methods.
func Generate(database schema.Schema, config Config) ([]byte, error) {
	if config.Package == "" {
		return nil, fmt.Errorf("codegen: package name is required")
	}
	dialect := database.Dialect
	if dialect == "" {
		dialect = schema.PostgreSQL
	}
	if dialect != schema.PostgreSQL && dialect != schema.MySQL && dialect != schema.SQLite {
		return nil, fmt.Errorf("codegen: unsupported SQL dialect %s", dialect)
	}
	tables := append([]schema.Table(nil), database.Tables...)
	sort.Slice(tables, func(i, j int) bool { return tables[i].Name < tables[j].Name })
	if err := validateForeignKeys(tables); err != nil {
		return nil, err
	}

	var output bytes.Buffer
	fmt.Fprintf(&output, "// Code generated by tiqq; DO NOT EDIT.\npackage %s\n\n", config.Package)
	dialectPackage, dialectName := "postgres", "PostgreSQL"
	if dialect == schema.MySQL {
		dialectPackage, dialectName = "mysql", "MySQL"
	} else if dialect == schema.SQLite {
		dialectPackage, dialectName = "sqlite", "SQLite"
	}
	output.WriteString("import (\n\t\"database/sql\"\n")
	if schemaUsesType(tables, dialect, "jsontext.Value") {
		output.WriteString("\t\"encoding/json/jsontext\"\n")
	}
	if schemaUsesType(tables, dialect, "uuid.UUID") {
		output.WriteString("\t\"uuid\"\n")
	}
	fmt.Fprintf(&output, "\n\t\"github.com/eji/tiqq\"\n\t\"github.com/eji/tiqq/%s\"\n)\n\n", dialectPackage)
	fmt.Fprintf(&output, "var tiqqSchema = tiqq.NewSchemaInfo(tiqq.%s)\n\n", dialectName)
	for _, table := range tables {
		writeTable(&output, table, dialect)
	}
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return nil, fmt.Errorf("codegen: format generated source: %w", err)
	}
	return formatted, nil
}

func schemaUsesType(tables []schema.Table, dialect schema.Dialect, typeName string) bool {
	for _, table := range tables {
		for _, column := range table.Columns {
			if goType(dialect, column) == typeName {
				return true
			}
		}
	}
	return false
}

func validateForeignKeys(tables []schema.Table) error {
	known := make(map[string]bool, len(tables))
	for _, table := range tables {
		known[table.Name] = true
	}
	for _, table := range tables {
		for _, foreignKey := range table.ForeignKeys {
			if !known[foreignKey.ReferencedTable] {
				return fmt.Errorf("codegen: foreign key %s references unknown table %s", foreignKey.Name, foreignKey.ReferencedTable)
			}
		}
	}
	return nil
}

func writeTable(output *bytes.Buffer, table schema.Table, dialect schema.Dialect) {
	typeName := exported(singular(table.Name))
	scope := typeName + "Scope"
	nullableType := "Nullable" + typeName + "TableDef"
	fmt.Fprintf(output, "type %s struct{}\n\ntype %sTableDef struct {\n\tref tiqq.TableRef\n", scope, typeName)
	for _, column := range table.Columns {
		fmt.Fprintf(output, "\t%s %s\n", exported(column.Name), columnType(dialect, scope, column, false))
	}
	output.WriteString("}\n\n")
	fmt.Fprintf(output, "type %s struct {\n", nullableType)
	for _, column := range table.Columns {
		fmt.Fprintf(output, "\t%s %s\n", exported(column.Name), columnType(dialect, scope, column, true))
	}
	output.WriteString("}\n\n")
	fmt.Fprintf(output, "var %sTable = %sTableDef{\n\tref: tiqqSchema.Table(%q),\n", typeName, typeName, table.Name)
	for _, column := range table.Columns {
		sumType, avgType, numeric := numericAggregateTypes(dialect, column.DBType)
		constructor := "RequiredColumn"
		typeArguments := fmt.Sprintf("%s, %s", scope, goType(dialect, column))
		if numeric {
			constructor = "RequiredNumericColumn"
			typeArguments = fmt.Sprintf("%s, %s, %s, %s", scope, goType(dialect, column), sumType, avgType)
		}
		if column.Nullable {
			constructor = "NullableColumn"
			if numeric {
				constructor = "NullableNumericColumn"
			}
		}
		fmt.Fprintf(output, "\t%s: tiqq.%s[%s](%q, %q),\n", exported(column.Name), constructor, typeArguments, table.Name, column.Name)
	}
	output.WriteString("}\n\n")
	fmt.Fprintf(output, "func (table %sTableDef) TiqqTableInfo() tiqq.TableInfo[%sTableDef, %s] {\n", typeName, typeName, nullableType)
	fmt.Fprintf(output, "return tiqq.NewTableInfo(table.ref, table, %s{\n", nullableType)
	for _, column := range table.Columns {
		function := "RebindNullable"
		_, _, numeric := numericAggregateTypes(dialect, column.DBType)
		if numeric {
			function = "RebindNullableNumeric"
		}
		if column.Nullable {
			function = "RebindExistingNullable"
			if numeric {
				function = "RebindExistingNullableNumeric"
			}
		}
		fmt.Fprintf(output, "\t%s: tiqq.%s[%s, %s](table.%s),\n", exported(column.Name), function, scope, scope, exported(column.Name))
	}
	output.WriteString("}, []tiqq.ForeignKey{")
	for _, foreignKey := range table.ForeignKeys {
		fmt.Fprintf(output, "{Columns: %#v, ReferencedTable: %q, ReferencedColumns: %#v},", foreignKey.Columns, foreignKey.ReferencedTable, foreignKey.ReferencedColumns)
	}
	output.WriteString("})\n}\n\n")
	fmt.Fprintf(output, "func (table %sTableDef) TiqqJoinSource() tiqq.JoinSourceInfo[%sTableDef, %s] { return tiqq.TableJoinSource(table.TiqqTableInfo()) }\n", typeName, typeName, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) LeftJoin[C, NC any, R tiqq.TableLike[C, NC]](right R) tiqq.Joined[%sTableDef, NC, %s, NC] { return tiqq.LeftJoin(table, right) }\n", typeName, typeName, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) InnerJoin[C, NC any, R tiqq.TableLike[C, NC]](right R) tiqq.Joined[%sTableDef, C, %s, NC] { return tiqq.InnerJoin(table, right) }\n", typeName, typeName, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) RightJoin[C, NC any, R tiqq.TableLike[C, NC]](right R) tiqq.Joined[%s, C, %s, NC] { return tiqq.RightJoin(table, right) }\n", typeName, nullableType, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) FullJoin[C, NC any, R tiqq.TableLike[C, NC]](right R) tiqq.Joined[%s, NC, %s, NC] { return tiqq.FullJoin(table, right) }\n", typeName, nullableType, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) CrossJoin[C, NC any, R tiqq.TableLike[C, NC]](right R) tiqq.Joined[%sTableDef, C, %s, NC] { return tiqq.CrossJoin(table, right) }\n", typeName, typeName, nullableType)
	fmt.Fprintf(output, "func (table %sTableDef) Where(predicates ...tiqq.Predicate) tiqq.Query { return tiqq.NewTableQuery(table).Where(predicates...) }\n", typeName)
	fmt.Fprintf(output, "func (table %sTableDef) Select(columns ...tiqq.Selection) tiqq.Query { return tiqq.NewTableQuery(table).Select(columns...) }\n", typeName)
	fmt.Fprintf(output, "func (table %sTableDef) GroupBy(columns ...tiqq.Selection) tiqq.Query { return tiqq.NewTableQuery(table).GroupBy(columns...) }\n", typeName)
	fmt.Fprintf(output, "func (table %sTableDef) Update() tiqq.UpdateQuery[%s] { return tiqq.NewUpdate[%s](table) }\n", typeName, scope, scope)
	fmt.Fprintf(output, "func (table %sTableDef) Delete() tiqq.DeleteQuery[%s] { return tiqq.NewDelete[%s](table) }\n", typeName, scope, scope)
	dialectPackage, marker := "postgres", "PostgreSQLMarker"
	if dialect == schema.MySQL {
		dialectPackage, marker = "mysql", "MySQLMarker"
	} else if dialect == schema.SQLite {
		dialectPackage, marker = "sqlite", "SQLiteMarker"
	}
	fmt.Fprintf(output, "func (table %sTableDef) Insert() %s.InsertQuery[%s] { return %s.NewInsert(tiqq.NewInsert[%s, tiqq.%s](table.ref, %#v, %#v, %#v)) }\n", typeName, dialectPackage, scope, dialectPackage, scope, marker, insertableColumns(table.Columns), requiredInsertColumns(table.Columns), uniqueColumns(table))
	fmt.Fprintf(output, "func (table %sTableDef) As(alias string) %sTableDef {\n", typeName, typeName)
	output.WriteString("table.ref = table.ref.As(alias)\n")
	for _, column := range table.Columns {
		function := "AliasColumn"
		if _, _, numeric := numericAggregateTypes(dialect, column.DBType); numeric {
			function = "AliasNumericColumn"
		}
		fmt.Fprintf(output, "table.%s = tiqq.%s[%s, %s](table.%s, alias)\n", exported(column.Name), function, scope, scope, exported(column.Name))
	}
	output.WriteString("return table\n}\n\n")
}

func insertableColumns(columns []schema.Column) []string {
	var result []string
	for _, column := range columns {
		if !column.Generated && !column.Identity {
			result = append(result, column.Name)
		}
	}
	return result
}

func requiredInsertColumns(columns []schema.Column) []string {
	var result []string
	for _, column := range columns {
		if !column.Nullable && column.Default == nil && !column.Generated && !column.Identity {
			result = append(result, column.Name)
		}
	}
	return result
}

func uniqueColumns(table schema.Table) [][]string {
	var result [][]string
	if table.PrimaryKey != nil {
		result = append(result, append([]string(nil), table.PrimaryKey.Columns...))
	}
	for _, key := range table.UniqueKeys {
		result = append(result, append([]string(nil), key.Columns...))
	}
	return result
}

func columnType(dialect schema.Dialect, scope string, column schema.Column, outer bool) string {
	value := goType(dialect, column)
	if sumType, avgType, numeric := numericAggregateTypes(dialect, column.DBType); numeric {
		if column.Nullable || outer {
			return fmt.Sprintf("tiqq.NumericColumn[%s, sql.Null[%s], %s, %s, %s]", scope, value, value, sumType, avgType)
		}
		return fmt.Sprintf("tiqq.NumericColumn[%s, %s, %s, %s, %s]", scope, value, value, sumType, avgType)
	}
	if column.Nullable || outer {
		return fmt.Sprintf("tiqq.Column[%s, sql.Null[%s], %s]", scope, value, value)
	}
	return fmt.Sprintf("tiqq.Column[%s, %s, %s]", scope, value, value)
}

func numericAggregateTypes(dialect schema.Dialect, databaseType string) (string, string, bool) {
	if isUUIDType(dialect, databaseType) || isJSONType(databaseType) {
		return "", "", false
	}
	if dialect == schema.SQLite {
		switch sqliteAffinity(databaseType) {
		case "integer":
			return "int64", "float64", true
		case "real":
			return "float64", "float64", true
		case "numeric":
			return "tiqq.Decimal", "tiqq.Decimal", true
		default:
			return "", "", false
		}
	}
	if dialect == schema.MySQL {
		switch databaseType {
		case "tinyint", "smallint", "mediumint", "int", "integer", "bigint", "decimal", "numeric":
			return "tiqq.Decimal", "tiqq.Decimal", true
		case "float", "double", "real":
			return "float64", "float64", true
		default:
			return "", "", false
		}
	}
	switch databaseType {
	case "int2", "smallint", "smallserial", "int4", "integer", "serial":
		return "int64", "tiqq.Decimal", true
	case "int8", "bigint", "bigserial", "numeric", "decimal":
		return "tiqq.Decimal", "tiqq.Decimal", true
	case "float4", "real":
		return "float32", "float64", true
	case "float8", "double precision":
		return "float64", "float64", true
	default:
		return "", "", false
	}
}

func goType(dialect schema.Dialect, column schema.Column) string {
	databaseType := column.DBType
	if isUUIDType(dialect, databaseType) {
		return "uuid.UUID"
	}
	if isJSONType(databaseType) {
		return "jsontext.Value"
	}
	if dialect == schema.SQLite {
		switch sqliteAffinity(databaseType) {
		case "integer":
			return "int64"
		case "real":
			return "float64"
		case "blob":
			return "[]byte"
		case "numeric":
			return "tiqq.Decimal"
		default:
			return "string"
		}
	}
	if dialect == schema.MySQL {
		switch databaseType {
		case "tinyint":
			if column.Unsigned {
				return "uint8"
			}
			return "int8"
		case "smallint":
			if column.Unsigned {
				return "uint16"
			}
			return "int16"
		case "mediumint", "int", "integer":
			if column.Unsigned {
				return "uint32"
			}
			return "int32"
		case "bigint":
			if column.Unsigned {
				return "uint64"
			}
			return "int64"
		case "bool", "boolean":
			return "bool"
		case "binary", "varbinary", "tinyblob", "blob", "mediumblob", "longblob":
			return "[]byte"
		case "float":
			return "float32"
		case "double", "real":
			return "float64"
		case "decimal", "numeric":
			return "tiqq.Decimal"
		default:
			return "string"
		}
	}
	switch databaseType {
	case "int8", "bigint", "bigserial":
		return "int64"
	case "int4", "integer", "serial":
		return "int32"
	case "int2", "smallint", "smallserial":
		return "int16"
	case "bool", "boolean":
		return "bool"
	case "bytea":
		return "[]byte"
	case "float4", "real":
		return "float32"
	case "float8", "double precision":
		return "float64"
	case "numeric", "decimal":
		return "tiqq.Decimal"
	default:
		return "string"
	}
}

func isUUIDType(dialect schema.Dialect, databaseType string) bool {
	return (dialect == schema.PostgreSQL || dialect == schema.SQLite) && strings.EqualFold(strings.TrimSpace(databaseType), "uuid")
}

func isJSONType(databaseType string) bool {
	normalized := strings.ToLower(strings.TrimSpace(databaseType))
	return normalized == "json" || normalized == "jsonb"
}

func sqliteAffinity(databaseType string) string {
	normalized := strings.ToUpper(strings.TrimSpace(databaseType))
	switch {
	case normalized == "" || strings.Contains(normalized, "BLOB"):
		return "blob"
	case strings.Contains(normalized, "INT"):
		return "integer"
	case strings.Contains(normalized, "CHAR"), strings.Contains(normalized, "CLOB"), strings.Contains(normalized, "TEXT"):
		return "text"
	case strings.Contains(normalized, "REAL"), strings.Contains(normalized, "FLOA"), strings.Contains(normalized, "DOUB"):
		return "real"
	default:
		return "numeric"
	}
}

func singular(name string) string {
	if strings.HasSuffix(name, "sses") {
		return strings.TrimSuffix(name, "es")
	}
	if strings.HasSuffix(name, "ies") {
		return strings.TrimSuffix(name, "ies") + "y"
	}
	if strings.HasSuffix(name, "s") {
		return strings.TrimSuffix(name, "s")
	}
	return name
}

func exported(name string) string {
	parts := strings.FieldsFunc(name, func(character rune) bool { return character == '_' || character == '-' })
	for index, part := range parts {
		upper := strings.ToUpper(part)
		if upper == "ID" {
			parts[index] = upper
			continue
		}
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		parts[index] = string(runes)
	}
	return strings.Join(parts, "")
}
